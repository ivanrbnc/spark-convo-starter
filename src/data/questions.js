export function getRandomQuestion(categoryId, usedIndices = []) {
  const pool = questions[categoryId];
  if (!pool) return null;
  const available = pool
    .map((q, i) => ({ q, i }))
    .filter(({ i }) => !usedIndices.includes(i));
  if (available.length === 0) return { question: pool[Math.floor(Math.random() * pool.length)], index: -1 };
  const pick = available[Math.floor(Math.random() * available.length)];
  return { question: pick.q, index: pick.i };
}
